const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { launch, createPage, assertReleased } = require('./harness.cjs');
const { fixtureState, installFixture } = require('./learning-fixture.cjs');
const baseUrl = process.argv[2] || 'http://127.0.0.1:13204';
const output = process.env.BROWSER_OUTPUT_DIR || '/tmp/chatterpal-int2-contract-browser';

(async () => {
  await fs.mkdir(output, { recursive: true });
  const browser = await launch();
  const reports = [];
  try {
    const { context, page, errors } = await createPage(browser, { force48k: true });
    const state = fixtureState();
    await installFixture(page, state);
    await page.goto(baseUrl);
    await page.getByRole('button', { name: '开始描述周末' }).waitFor();
    await page.screenshot({ path: path.join(output, 'today-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: '开始描述周末' }).click();
    await page.getByRole('textbox', { name: '我的任务回答' }).fill('I go hiking yesterday.');
    await page.getByRole('button', { name: '给我一个开头' }).click();
    await page.getByText('Last weekend, I…', { exact: true }).waitFor();
    assert.equal(await page.getByRole('textbox', { name: '我的任务回答' }).inputValue(), 'I go hiking yesterday.');
    await page.getByRole('button', { name: '学习记录', exact: true }).click();
    await page.getByRole('button', { name: '返回本次练习' }).click();
    assert.equal(await page.getByRole('textbox', { name: '我的任务回答' }).inputValue(), 'I go hiking yesterday.');
    state.holdTurn = true;
    await page.getByRole('button', { name: '发送任务回答' }).click();
    await page.getByText(/正在处理这次练习/).waitFor();
    assert.equal(state.requestIds.length, 3);
    await page.reload();
    await page.getByText(/正在处理这次练习/).waitFor();
    state.releaseTurn();
    await page.getByRole('button', { name: '返回本次练习' }).waitFor();
    await page.getByRole('button', { name: '返回本次练习' }).click();
    await page.getByText('Who did you go with?', { exact: true }).waitFor();
    assert.equal(state.requestIds.length, 3, 'Reload recovers operation without another mutation');
    await page.getByRole('button', { name: '结束对话，查看反馈' }).click();
    await page.getByRole('button', { name: '针对这一句重练' }).click();
    assert.equal(await page.getByRole('textbox', { name: '参考文本' }).count(), 0);
    await page.getByRole('textbox', { name: '我的新表达' }).fill('I went hiking yesterday.');
    await page.getByText('第一次练习', { exact: true }).waitFor();
    await page.getByRole('button', { name: '保存这次重练' }).click();
    await page.getByText('第 2 次练习', { exact: true }).waitFor();
    await page.getByRole('textbox', { name: '我的新表达' }).fill('Yesterday I went hiking with friends.');
    await page.getByRole('button', { name: '保存这次重练' }).click();
    await page.getByText('第 3 次练习', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'retry-desktop.png'), fullPage: true });
    assert.equal(await page.getByRole('button', { name: '保存到次日复习' }).count(), 0);
    await page.getByRole('button', { name: '到期复习', exact: true }).click();
    await page.locator('[role="status"]').filter({ hasText: '复习功能尚未接入' }).waitFor();
    assert.equal(await page.getByRole('button', { name: '开始这项复习' }).count(), 0);
    reports.push({ suite: 'contract-task-retry-reload-review-unavailable', attempts: state.session.attempts.length, mutations: state.requestIds.length, errors });

    await page.getByRole('button', { name: '返回本次练习' }).click();
    await page.getByRole('button', { name: '练这一句', exact: true }).click();
    await page.getByRole('button', { name: '开始录音', exact: true }).click();
    await page.getByRole('button', { name: '停止录音', exact: true }).waitFor();
    await page.waitForFunction(() => window.__probe.captureBatches.some(count => count >= 5));
    await page.getByRole('button', { name: '停止录音', exact: true }).click();
    await page.getByRole('button', { name: '试听本次录音', exact: true }).waitFor();
    await page.getByRole('combobox', { name: '学习音频播放速度' }).selectOption('0.75');
    await page.getByRole('button', { name: '试听本次录音', exact: true }).click();
    await page.waitForFunction(() => { const audio = document.querySelector('.learning-workspace audio'); return audio && !audio.paused && audio.playbackRate === 0.75; });
    await page.getByRole('button', { name: '学习记录', exact: true }).click();
    await assertReleased(page);
    await page.getByRole('button', { name: '返回本次练习' }).click();
    await page.getByRole('button', { name: '试听本次录音', exact: true }).waitFor();
    await page.getByRole('button', { name: '识别并核对录音', exact: true }).click();
    await page.getByRole('textbox', { name: '核对录音文字', exact: true }).waitFor();
    await page.getByRole('button', { name: '确认文字并提交', exact: true }).click();
    await page.getByText('第 4 次练习', { exact: true }).waitFor();
    const captureIndex = await page.evaluate(() => window.__probe.captureBatches.length);
    await page.getByRole('button', { name: '开始录音', exact: true }).click();
    await page.getByRole('button', { name: '停止录音', exact: true }).waitFor();
    await page.waitForFunction(index => window.__probe.captureBatches[index] >= 2, captureIndex);
    await page.getByRole('button', { name: '学习记录', exact: true }).click();
    await assertReleased(page);
    await page.getByRole('button', { name: '打开练习记录' }).click();
    await page.getByRole('button', { name: '针对这一句重练' }).click();
    await page.setViewportSize({ width: 375, height: 812 });
    await page.screenshot({ path: path.join(output, 'retry-mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.setViewportSize({ width: 812, height: 375 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.getByRole('button', { name: '开始录音', exact: true }).click();
    await page.getByRole('button', { name: '停止录音', exact: true }).waitFor();
    await page.getByRole('button', { name: '对话练习', exact: true }).click();
    await assertReleased(page);
    reports.push({ suite: 'mobile-audio-speed-upload-and-microphone-release', playbackRate: 0.75, attempts: state.session.attempts.length, errors });
    assert.deepEqual(errors, []);
    await context.close();
    await fs.writeFile(path.join(output, 'results.json'), JSON.stringify(reports, null, 2));
    console.log(JSON.stringify({ output, reports }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
